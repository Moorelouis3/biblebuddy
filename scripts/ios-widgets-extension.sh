#!/usr/bin/env bash
# Add the home-screen widgets extension to the generated Xcode project
# (Louis, 2026-11-18). Four widgets in one extension: Verse of the Day,
# Streak, My Study, Bible Lock. Source: native/ios-extensions/BibleBuddyWidgets.
#
# Same pattern as scripts/ios-bible-lock-extension.sh, and the same four traps
# that one hit on 2026-10-17 are handled the same way here:
#   - PRODUCT_NAME set, or the product builds as ".appex" and the embed phase
#     produces two commands for the same path;
#   - bare filenames in the group, or the paths double up;
#   - CFBundleExecutable and version placeholders in the Info.plist;
#   - a provisioning profile for net.mybiblebuddy.app.widgets committed in
#     ios-signing/, which scripts/ios-install-profile.sh installs.
#
# ios/ is regenerated by `npx cap add ios` on every build, so this runs after
# generation. Run from the repo root, after `cap sync` and before `xcodebuild`.
set -euo pipefail

PROJECT="ios/App/App.xcodeproj"
SOURCE_DIR="native/ios-extensions/BibleBuddyWidgets"
TARGET_NAME="BibleBuddyWidgets"
DEST="ios/App/$TARGET_NAME"

if [ ! -d "$PROJECT" ]; then
  echo "No Xcode project at $PROJECT - run 'npx cap add ios' first." >&2
  exit 1
fi

mkdir -p "$DEST"
cp "$SOURCE_DIR"/*.swift "$DEST/"
cp "$SOURCE_DIR/Info.plist" "$DEST/"
cp "$SOURCE_DIR/BibleBuddyWidgets.entitlements" "$DEST/"

# The app writes the widgets' snapshot into the App Group, so the app target
# needs it too. The Bible lock step adds it already; this is for a build that
# ever runs without that step.
APP_ENTITLEMENTS="ios/App/App/App.entitlements"
if [ -f "$APP_ENTITLEMENTS" ] && ! grep -q "application-groups" "$APP_ENTITLEMENTS"; then
  /usr/libexec/PlistBuddy -c "Add :com.apple.security.application-groups array" "$APP_ENTITLEMENTS"
  /usr/libexec/PlistBuddy -c "Add :com.apple.security.application-groups:0 string group.net.mybiblebuddy.app" "$APP_ENTITLEMENTS"
  echo "Added the App Group to the app target's entitlements."
fi

ruby <<'RUBY'
require 'xcodeproj'

project_path = 'ios/App/App.xcodeproj'
target_name  = 'BibleBuddyWidgets'
project = Xcodeproj::Project.open(project_path)

if project.targets.any? { |t| t.name == target_name }
  puts "#{target_name} is already in the project; leaving it alone."
  exit 0
end

app = project.targets.find { |t| t.name == 'App' } or abort 'No App target found.'

ext = project.new_target(:app_extension, target_name, :ios, '16.0', nil, :swift)

# Bare filenames: the group already carries the folder name.
group = project.main_group.new_group(target_name, target_name)
ref = group.new_reference('BibleBuddyWidgets.swift')
ext.add_file_references([ref])
group.new_reference('Info.plist')
group.new_reference('BibleBuddyWidgets.entitlements')

# WidgetKit and SwiftUI are linked by the Swift imports themselves.

ext.build_configurations.each do |config|
  s = config.build_settings
  s['PRODUCT_NAME'] = target_name
  # Placeholders; the version step's agvtool -all writes the real numbers.
  s['MARKETING_VERSION'] = '1.0'
  s['CURRENT_PROJECT_VERSION'] = '1'
  s['PRODUCT_BUNDLE_IDENTIFIER'] = 'net.mybiblebuddy.app.widgets'
  s['INFOPLIST_FILE'] = "#{target_name}/Info.plist"
  s['CODE_SIGN_ENTITLEMENTS'] = "#{target_name}/BibleBuddyWidgets.entitlements"
  s['IPHONEOS_DEPLOYMENT_TARGET'] = '16.0'
  s['SWIFT_VERSION'] = '5.0'
  s['TARGETED_DEVICE_FAMILY'] = '1,2'
  s['GENERATE_INFOPLIST_FILE'] = 'NO'
  s['SKIP_INSTALL'] = 'YES'
  s['APPLICATION_EXTENSION_API_ONLY'] = 'YES'
  s['DEVELOPMENT_TEAM'] = app.build_configurations.first.build_settings['DEVELOPMENT_TEAM']
end

app.add_dependency(ext)
# Reuse the Bible lock's embed phase when it exists: two phases embedding into
# the same PlugIns folder is legal but untidy, and one is easier to read.
embed = app.copy_files_build_phases.find { |p| p.name == 'Embed App Extensions' } ||
        app.new_copy_files_build_phase('Embed App Extensions')
embed.symbol_dst_subfolder_spec = :plug_ins
embed.add_file_reference(ext.product_reference)

project.save
puts "Added #{target_name} to the Xcode project."
RUBY

echo "--- widget extension entitlements ---"
cat "$DEST/BibleBuddyWidgets.entitlements"
