/**
 * Let an https://www.mybiblebuddy.net link open the Android app, not Chrome.
 *
 * Louis, 2026-11-08: "the emails open the web version of the app in chrome on
 * my iphone, can we make it open the app on ios or android instead of the
 * website?" Google calls this an App Link. It needs two halves, and neither
 * does anything alone:
 *
 *   1. this intent-filter, carrying android:autoVerify="true"
 *   2. /.well-known/assetlinks.json on the domain, naming the app's SHA-256
 *      signing fingerprint (app/api/well-known/assetlinks/route.ts)
 *
 * On first install Android fetches that file and checks the fingerprint
 * against the certificate the app was actually signed with. If they match,
 * every link to the host opens the app silently. If they do not, nothing
 * breaks - the link simply opens the browser as it always did.
 *
 * android/ is gitignored and regenerated by `npx cap add android` on every
 * Codemagic build, which is why this is a patch script run afterwards rather
 * than a committed manifest - the same reason scripts/ios-*.sh exist.
 *
 * OFF BY DEFAULT, and the reason is Android 7 to 11.
 *
 * From Android 12 an unverified intent-filter does nothing at all: the link
 * keeps opening the browser until verification passes. Below 12 there is no
 * verification, so the filter alone makes Android offer a chooser - "Open
 * with: Chrome / Bible Buddy" - on every single link. minSdkVersion is 24
 * here, so those users exist. Shipping the filter before the fingerprint is
 * published would hand them a dialog and no benefit, so the whole feature
 * turns on in one go: ANDROID_APP_LINKS=on here, ANDROID_APP_LINK_SHA256 on
 * the website. See docs/DEEP_LINKS.md.
 *
 *   ANDROID_APP_LINKS=on node scripts/android-deep-links.mjs
 */

import fs from "node:fs";

const MANIFEST = "android/app/src/main/AndroidManifest.xml";

/**
 * www only, and deliberately.
 *
 * mybiblebuddy.net 307s to www.mybiblebuddy.net. Android would honour a filter
 * on the apex, but the assetlinks file has to be readable on whatever host is
 * listed and the apex only redirects - so www is the one host that can both
 * serve the proof and receive the link. The email templates were moved onto
 * www in the same change for the same reason.
 */
const HOST = "www.mybiblebuddy.net";

/** Lets this run twice without stacking two identical filters. */
const MARKER = `android:host="${HOST}"`;

const FILTER = `
            <!-- Universal/App Links: see scripts/android-deep-links.mjs -->
            <intent-filter android:autoVerify="true">
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="https" android:host="${HOST}" />
            </intent-filter>
`;

if (process.env.ANDROID_APP_LINKS !== "on") {
  console.log(
    "Android App Links: off (set ANDROID_APP_LINKS=on to add the intent-filter)",
  );
  process.exit(0);
}

if (!fs.existsSync(MANIFEST)) {
  console.error(`No manifest at ${MANIFEST} - run 'npx cap add android' first.`);
  process.exit(1);
}

const original = fs.readFileSync(MANIFEST, "utf8");

if (original.includes(MARKER)) {
  console.log(`Android App Links: already present for ${HOST}; leaving the manifest alone.`);
  process.exit(0);
}

/**
 * Anchored on the launcher intent-filter's closing tag, which exists exactly
 * once and sits inside MainActivity. Matching on it means the new filter lands
 * in the right activity without parsing XML, and a Capacitor change that moves
 * it is caught here rather than producing a silently wrong manifest.
 */
const ANCHOR = `                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
`;

const occurrences = original.split(ANCHOR).length - 1;
if (occurrences !== 1) {
  console.error(
    `Expected exactly one LAUNCHER intent-filter in ${MANIFEST}, found ${occurrences} - refusing to guess.`,
  );
  process.exit(1);
}

const patched = original.replace(ANCHOR, `${ANCHOR}${FILTER}`);
fs.writeFileSync(MANIFEST, patched, "utf8");

console.log(`Android App Links: ON - added an intent-filter for https://${HOST}`);
console.log("  Links open the app only once Android verifies it against");
console.log(`  https://${HOST}/.well-known/assetlinks.json`);
