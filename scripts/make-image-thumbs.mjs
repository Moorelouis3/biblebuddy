/**
 * Small copies of the pictures that are shown small.
 *
 *   node scripts/make-image-thumbs.mjs
 *
 * Why: a study cover is a 500 to 900 KB PNG and the app shows it about 75 to
 * 200 px wide on the shelf, the Home widgets and the study pickers. Every one
 * was downloaded at full size to be drawn as a thumbnail
 * (docs/SPEED_REPORT_2026-11-25.md, cause 8).
 *
 * This writes a WebP copy of each under public/thumbs/, and the list of what
 * exists to lib/imageThumbs.generated.ts. lib/imageThumb.ts reads that list,
 * so a cover with no small copy simply keeps using the original; nothing can
 * end up pointing at a file that is not there.
 *
 * It only makes what is missing or older than its source. The copies and the
 * list are committed, so a build does not run this.
 *
 * A NEW STUDY COVER: add its file name to STUDY_COVERS below, run this, and
 * commit what it wrote. Forgetting is harmless (the full cover is used), just
 * slower.
 *
 * Blog banners are not here on purpose: Home already draws them through
 * next/image, which resizes them itself.
 */
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const PUBLIC = join(process.cwd(), "public");
const OUT = join(PUBLIC, "thumbs");

/** devotionals.cover_image values, plus the shelf covers in lib/libraryCatalog.ts. */
const STUDY_COVERS = [
  "TheDeliveranceofMoses.png",
  "TheCovenantatSinai.png",
  "ThePresenceofGod.png",
  "ThegolinessbeforeGod.png",
  "Wildernessjourneycover.png",
  "RebellionintheWilderness.png",
  "promieslandcover.png",
  "callingofmosesdevotional.png",
  "heartofdaviddevotional.png",
  "thecourageofdaniel.png",
  "theriseofester.png",
  "TheTestingofJospehnewcover.png",
  "Day1cover.png",
  "21-women-of-the-bible-cover.png",
  "obedienceofabraham28day.png",
  "thefallofman.png",
  "Floodofnoah.png",
  "ThePromiseThroughIsaac.png",
  "TheWrestlingofJacob.png",
  "disciplesofjesusdevotional.png",
  "transformingofpauldevotional.png",
  "faithofjob.png",
  "Wisdomofproverbsnewcover.png",
  "tempting-of-jesus-cover.png",
  "beginning-of-everything-cover.webp",
  "higher-hope.webp",
  "bible-in-one-year-cover.png",
];

// Twice the widest size each is drawn at, for sharp phone screens.
const COVER_WIDTH = 400;

const thumbName = (file) => file.replace(/\.[^.]+$/, "") + ".webp";

async function make(sourcePath, outPath, width) {
  if (existsSync(outPath) && statSync(outPath).mtimeMs >= statSync(sourcePath).mtimeMs) return false;
  await sharp(sourcePath).resize({ width, withoutEnlargement: true }).webp({ quality: 78 }).toFile(outPath);
  return true;
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  /** source url -> thumb url */
  const map = {};
  let made = 0;

  for (const file of STUDY_COVERS) {
    const source = join(PUBLIC, file);
    if (!existsSync(source)) {
      console.warn(`  missing cover, skipped: ${file}`);
      continue;
    }
    if (await make(source, join(OUT, thumbName(file)), COVER_WIDTH)) made += 1;
    map[`/${file}`] = `/thumbs/${thumbName(file)}`;
  }

  const lines = Object.keys(map)
    .sort()
    .map((source) => `  ${JSON.stringify(source)}: ${JSON.stringify(map[source])},`);
  writeFileSync(
    join(process.cwd(), "lib", "imageThumbs.generated.ts"),
    [
      "// GENERATED by scripts/make-image-thumbs.mjs. Do not edit by hand.",
      "// Every picture that has a small copy under public/thumbs, and where it is.",
      "export const IMAGE_THUMBS: Record<string, string> = {",
      ...lines,
      "};",
      "",
    ].join("\n"),
  );

  console.log(`image thumbs: ${Object.keys(map).length} listed, ${made} made this run`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
