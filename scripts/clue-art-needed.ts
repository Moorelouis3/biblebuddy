/**
 * npx tsx scripts/clue-art-needed.ts
 *
 * Writes docs/clue-card-art-needed.md and .csv: every Bible Clue answer in
 * the question bank that has no card art yet, by Genesis chapter (Louis,
 * 2026-11-22: "the new questions don't have card images anymore, I need a
 * by-chapter list of icons we need to make with the reveal and mysterious
 * versions").
 *
 * - A person, place or object gets its own pair (mystery silhouette +
 *   revealed picture), listed once under the chapter where it first appears,
 *   with every question it would cover.
 * - A phrase answer ("It was very good", "The fourth day") cannot be drawn
 *   as a thing; those questions share one chapter card per chapter.
 *
 * File names are the art's slug, so dropping the files into
 * public/games/clue/genesis/art/ is all the wiring needed (lib/clueGame/bank
 * looks them up by slug).
 */
import { writeFileSync } from "node:fs";
import { BANK_ITEMS } from "../lib/clueGame/bank";
import { artSlug, isDrawable } from "../lib/clueGame/bank/art";

type Entry = { slug: string; answer: string; category: string; chapter: number; questions: string[] };
const subjects = new Map<string, Entry>();
const phrases = new Map<number, string[]>();

for (const q of [...BANK_ITEMS].sort((a, b) => a.chapter - b.chapter)) {
  if (q.mystery) continue; // already has a deck card's art
  if (!isDrawable(q.answerText, q.category)) {
    phrases.set(q.chapter, [...(phrases.get(q.chapter) || []), `${q.question} → ${q.answerText}`]);
    continue;
  }
  const slug = artSlug(q.answerText);
  const e = subjects.get(slug) || { slug, answer: q.answerText, category: q.category, chapter: q.chapter, questions: [] };
  e.questions.push(q.id);
  subjects.set(slug, e);
}

const byChapter = new Map<number, Entry[]>();
for (const e of subjects.values()) byChapter.set(e.chapter, [...(byChapter.get(e.chapter) || []), e]);
const label = (c: string) => (c === "person" ? "Person" : c === "place" ? "Place" : "Thing");

let md = `# Bible Clue: card art to make\n\nGenerated by \`npx tsx scripts/clue-art-needed.ts\`. Every answer in the Genesis question bank that has no card picture yet.\n\n`;
md += `**${subjects.size} pictures to make** (each as a pair: a mystery silhouette and a revealed picture), plus **${phrases.size} chapter cards** for the answers that are phrases, not things.\n\n`;
md += `Same style as the existing deck cards (Joseph, Noah, Beersheba): the mystery one is the dark silhouette, the reveal one is the full-colour picture.\n\n`;
md += `File names: \`<file>-mystery.webp\` and \`<file>-reveal.webp\` (or .png; I convert them), into public/games/clue/genesis/art/. A chapter card is \`chapter-<NN>-mystery\` / \`chapter-<NN>-reveal\`.\n\n`;
const csv = ["chapter,category,answer,file,mystery_file,reveal_file,questions"];
for (let ch = 1; ch <= 50; ch += 1) {
  const list = (byChapter.get(ch) || []).sort((a, b) => a.category.localeCompare(b.category) || a.answer.localeCompare(b.answer));
  const ph = phrases.get(ch) || [];
  if (!list.length && !ph.length) continue;
  md += `## Genesis ${ch}\n\n`;
  if (list.length) {
    md += `| | Picture | File | Used by |\n|---|---|---|---|\n`;
    for (const e of list) {
      md += `| ${label(e.category)} | ${e.answer} | \`${e.slug}\` | ${e.questions.length} question${e.questions.length > 1 ? "s" : ""} |\n`;
      csv.push([ch, label(e.category), `"${e.answer.replace(/"/g, '""')}"`, e.slug, `${e.slug}-mystery.webp`, `${e.slug}-reveal.webp`, e.questions.length].join(","));
    }
    md += `\n`;
  }
  if (ph.length) {
    const nn = String(ch).padStart(2, "0");
    md += `**Chapter card** \`chapter-${nn}\`: a scene for Genesis ${ch}, used by ${ph.length} phrase answer${ph.length > 1 ? "s" : ""}.\n\n`;
    csv.push([ch, "Chapter card", `"Genesis ${ch} scene"`, `chapter-${nn}`, `chapter-${nn}-mystery.webp`, `chapter-${nn}-reveal.webp`, ph.length].join(","));
  }
}
writeFileSync("docs/clue-card-art-needed.md", md);
writeFileSync("docs/clue-card-art-needed.csv", csv.join("\n") + "\n");
console.log(`${subjects.size} pictures, ${phrases.size} chapter cards`);
