#!/usr/bin/env bash
# Raise the generated iOS project to iOS 16.
#
# Why this exists (2026-10-17): the Bible lock plugin declares
# platforms: [.iOS(.v16)] in its Package.swift, because ManagedSettingsStore
# (named:) and Apple's app picker only settled in 16. Capacitor generates
# CapApp-SPM at .iOS(.v15) and makes the app depend on every plugin, so Swift
# Package Manager refuses to resolve the graph - a package cannot depend on
# one with a higher minimum platform. Resolution failing is why xcodebuild
# could not even read the project:
#
#   Failed to show build settings ios/App/App.xcodeproj
#
# which killed builds 9, 10 and 11 and has killed every build since the plugin
# landed on 2026-10-15.
#
# The alternative was to lower the plugin to 15 and sprinkle @available(iOS
# 16) through its Swift, which is more code to go wrong in a place no one can
# compile without a Mac. Raising the floor is one line and honest: the feature
# needs 16, and 16 runs on every iPhone from the 8 onwards.
#
# ios/ is regenerated by `npx cap add ios` on every build, so like the
# Info.plist keys, the icon and the entitlements, this is applied after
# generation rather than committed. Run from the repo root, after `cap sync`.
set -euo pipefail

TARGET_VERSION="16.0"
SPM_PACKAGE="ios/App/CapApp-SPM/Package.swift"
PROJECT="ios/App/App.xcodeproj/project.pbxproj"

if [ ! -f "$SPM_PACKAGE" ]; then
  echo "No $SPM_PACKAGE - run 'npx cap sync ios' first." >&2
  exit 1
fi

# The file says DO NOT MODIFY because Capacitor rewrites it on every sync.
# That is exactly why this runs after the sync and never commits the result.
sed -i '' 's/platforms: \[\.iOS(\.v15)\]/platforms: [.iOS(.v16)]/' "$SPM_PACKAGE"
grep -q 'platforms: \[\.iOS(\.v16)\]' "$SPM_PACKAGE" || {
  echo "Could not raise the platform in $SPM_PACKAGE - Capacitor may have changed its template:" >&2
  grep -n "platforms:" "$SPM_PACKAGE" >&2
  exit 1
}
echo "CapApp-SPM now targets iOS $TARGET_VERSION."

sed -i '' "s/IPHONEOS_DEPLOYMENT_TARGET = 15.0/IPHONEOS_DEPLOYMENT_TARGET = $TARGET_VERSION/g" "$PROJECT"
echo "Xcode targets: $(grep -c "IPHONEOS_DEPLOYMENT_TARGET = $TARGET_VERSION" "$PROJECT") build configurations at iOS $TARGET_VERSION."
