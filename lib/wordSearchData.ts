function slugFor(book: string) {
  return book.trim().toLowerCase().replace(/\s+/g, "-");
}

export const WORD_SEARCH_BOOKS: WordSearchBook[] = BIBLE_BOOKS.map((book) => ({
  book,
  slug: slugFor(book),
  words: (RAW[book] || []).map(([label, explanation, reference, match]) => {
    const [chapter, verse] = reference.split(":").map(Number);
    return {
      label,
      letters: normalizeLetters(label),
      explanation,
      chapter,
      verse,
      reference: `${book} ${chapter}:${verse}`,
      match: match || label,
    };
  }),
}));

export function getWordSearchBook(slugOrName: string | null | undefined): WordSearchBook | null {
  const wanted = slugFor(String(slugOrName || "").replace(/-/g, " "));
  return WORD_SEARCH_BOOKS.find((entry) => entry.slug === wanted) ?? null;
}

