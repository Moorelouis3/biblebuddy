export type EmailDay = 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8;
export type EmailVersion = "a" | "a_pro" | "b" | "c";

export function getEmailTemplate(day: EmailDay, version?: EmailVersion) {
  const templateKey = getTemplateKey(day, version);
  return (EMAIL_TEMPLATES as Record<string, { subject: string; body: string }>)[templateKey];
}

export function getTemplateKey(day: EmailDay, version?: EmailVersion): keyof typeof EMAIL_TEMPLATES {
  if (day === 1) return "day1_welcome";
  if (day === 2) return "day2_change";
  if (day === 3) return "day3_audio";
  if (day === 4 && version === "a_pro") return "day4_version_a_pro";
  if (day === 4 && version === "b") return "day4_version_b";
  if (day === 4 && version === "c") return "day4_version_c";
  if (day === 4) return "day4_version_a";
  if (day === 5) return "day5_study_notes";
  if (day === 6) return "day6_community";
  if (day === 7) return "day7_why_built";
  if (day === 8 && version === "a_pro") return "day8_version_a_pro";
  if (day === 8 && version === "b") return "day8_version_b";
  if (day === 8 && version === "c") return "day8_version_c";
  if (day === 8) return "day8_version_a";
  throw new Error(`Unknown email template: day${day}${version ? `_${version}` : ""}`);
}
