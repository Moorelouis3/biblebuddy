/**
 * Names this app (or a sign-up form) has stored when it had nothing real.
 * Compared lowercased with all spaces, dots, dashes and underscores removed,
 * so "BibleBuddy User", "Bible Buddy User" and "bible_buddy_user" are one.
 *
 * Deliberately NOT "bible buddy": that is the official account's chosen name
 * (it posts the Verse of the Day). Real members cannot be called just that -
 * the official account is the only one, and it never signs in to the app.
 */
const PLACEHOLDER_COMPACT = new Set([
  "biblebuddyuser",
  "biblebuddymember",
  "biblebuddyfriend",
  "buddy",
  "user",
  "newuser",
  "member",
  "newmember",
  "guest",
  "guestuser",
  "anonymous",
  "anon",
  "firstlast",
  "firstnamelastname",
  "name",
  "noname",
  "unknown",
  "test",
  "testuser",
]);

/** Words that are never a real first or last name on their own. */
const PLACEHOLDER_PARTS = new Set(["user", "member", "guest", "anonymous", "unknown", "null", "undefined"]);

function compact(value: string): string {
  return value.toLowerCase().replace(/[\s._-]+/g, "");
}

function clean(value: string | null | undefined): string {
  return (value || "").replace(/\s+/g, " ").trim();
}

/**
 * Placeholder or autogenerated? Empty, one of ours, the email prefix the app
 * once wrote at sign-up, or a "user_1a2b3c" / "User 189DE35E" style handle.
 */
export function isPlaceholderName(name: string | null | undefined, email?: string | null): boolean {
  const trimmed = clean(name);
  if (!trimmed) return true;
  if (PLACEHOLDER_COMPACT.has(compact(trimmed))) return true;
  const emailPrefix = email ? email.split("@")[0].trim().toLowerCase() : "";
  if (emailPrefix && trimmed.toLowerCase() === emailPrefix) return true;
  if (/^(user|member|guest|buddy)[\s_-]*[0-9a-f]{2,}$/i.test(trimmed)) return true;
  if (/@/.test(trimmed)) return true;
  return false;
}

export type NamePartResult = { ok: true; value: string } | { ok: false; error: string };

/**
 * Permissive about shape, strict about substance. "van der Westhuizen",
 * "O'Neill", "Jean-Baptiste", "Nel", "Ng" and non-Latin scripts all pass.
 * Empty, digits, addresses, URLs and placeholder words do not.
 */
export function validateNamePart(raw: string | null | undefined, label: "first" | "last"): NamePartResult {
  const value = clean(raw);
  const which = label === "first" ? "first name" : "last name";
  if (!value) return { ok: false, error: `Please enter your ${which}.` };
  if (value.length > 40) return { ok: false, error: `That ${which} is too long.` };
  if (!/\p{L}/u.test(value)) return { ok: false, error: `Please enter your real ${which}.` };
  if (/\d/.test(value)) return { ok: false, error: `A ${which} should not contain numbers.` };
  if (/[@/\\<>]/.test(value) || /https?:/i.test(value)) {
    return { ok: false, error: `Please enter your ${which}, not an address.` };
  }
  if (PLACEHOLDER_PARTS.has(value.toLowerCase()) || PLACEHOLDER_COMPACT.has(compact(value))) {
    return { ok: false, error: `Please enter your real ${which}.` };
  }
  return { ok: true, value };
}

/** Validates both halves and the joined name. */
export function validateFullName(
  firstName: string | null | undefined,
  lastName: string | null | undefined,
  email?: string | null,
): { ok: true; firstName: string; lastName: string; fullName: string } | { ok: false; error: string } {
  const first = validateNamePart(firstName, "first");
  if (!first.ok) return first;
  const last = validateNamePart(lastName, "last");
  if (!last.ok) return last;
  const fullName = `${first.value} ${last.value}`;
  if (isPlaceholderName(fullName, email)) return { ok: false, error: "Please enter your real name." };
  return { ok: true, firstName: first.value, lastName: last.value, fullName };
}

/** A usable stored picture: an http(s) URL. Nothing else renders as one. */
export function hasProfilePicture(url: string | null | undefined): boolean {
  const value = (url || "").trim();
  return /^https?:\/\/\S+$/i.test(value);
}

export type ProfileFields = {
  display_name?: string | null;
  username?: string | null;
  first_name?: string | null;
  last_name?: string | null;
  profile_image_url?: string | null;
};

export type ProfileCompleteness = {
  complete: boolean;
  missing: { firstName: boolean; lastName: boolean; photo: boolean };
  /** Best guess at what to prefill the form with. */
  firstName: string;
  lastName: string;
  profileImageUrl: string | null;
};

/**
 * display_name is the field every screen reads (feed, comments, profile), so
 * it is the source of truth. It has to split into a first and a last part that
 * both validate, and must not be a placeholder. The structured first_name /
 * last_name columns (2026-11-13) are only used to prefill when display_name
 * is unusable - settings and the profile editor write display_name alone, so
 * the columns can be stale.
 *
 * A missing profile_stats row (null) is simply incomplete. A FAILED read is
 * not this function's business: callers must treat it as unknown.
 */
export function evaluateProfile(profile: ProfileFields | null | undefined, email?: string | null): ProfileCompleteness {
  const stored = clean(profile?.display_name) || clean(profile?.username);
  const parts = stored.split(" ").filter(Boolean);
  let firstName = parts.length >= 2 ? parts[0] : "";
  let lastName = parts.length >= 2 ? parts.slice(1).join(" ") : "";
  const placeholder = isPlaceholderName(stored, email);

  const firstOk = !placeholder && validateNamePart(firstName, "first").ok;
  const lastOk = !placeholder && validateNamePart(lastName, "last").ok;

  if (!firstOk || !lastOk) {
    // Prefill only - the stored display_name is what has to be fixed, so a
    // usable prefill never counts as complete. Keep a real single name
    // ("Mary") as the first name, else the structured columns if real.
    const colFirst = clean(profile?.first_name);
    const colLast = clean(profile?.last_name);
    const single = parts.length === 1 && !placeholder ? parts[0] : "";
    const pick = (a: string, b: string, label: "first" | "last") =>
      validateNamePart(a, label).ok ? a : validateNamePart(b, label).ok ? b : "";
    firstName = pick(firstOk ? firstName : single, colFirst, "first");
    lastName = pick(lastOk ? lastName : "", colLast, "last");
  }

  const photo = hasProfilePicture(profile?.profile_image_url);
  return {
    complete: firstOk && lastOk && photo,
    missing: { firstName: !firstOk, lastName: !lastOk, photo: !photo },
    firstName,
    lastName,
    profileImageUrl: photo ? (profile?.profile_image_url as string).trim() : null,
  };
}

/**
 * Where the gate never appears. Public pages (lib/publicRoutes.ts) plus the
 * signed-in doors that must stay open while a profile is incomplete: auth
 * callbacks, account deletion, support and logout. Profile completion is
 * itself an overlay, so it needs no route of its own.
 */
const GATE_EXEMPT_PREFIXES = ["/auth", "/logout", "/delete-account", "/contact", "/reset-password", "/login", "/signup"];

export function isProfileGateExemptPath(pathname: string | null | undefined, isPublicPath: (p: string) => boolean): boolean {
  const raw = pathname || "/";
  const path = raw.length > 1 && raw.endsWith("/") ? raw.slice(0, -1) : raw;
  if (isPublicPath(path)) return true;
  return GATE_EXEMPT_PREFIXES.some((prefix) => path === prefix || path.startsWith(`${prefix}/`));
}
